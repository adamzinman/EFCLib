#!/usr/bin/env python3
"""
Add an existing Perspective project export (a zip with project.json at its root) to the repo.

    python3 tools/import_project_zip.py EFC_IOFaceplates.zip [more.zip ...] [--name NewName]

Unzips into imported/<Name>/ (Name = the zip's project.json title, or --name), normalises JSON to LF
with a trailing newline, and records the source in imported/IMPORTED.md. Imported projects have no
generator here, so build.py copies them unchanged into the merged EFC_Library project. Add the name to
IMPORTED_PARTS in build.py the first time.
"""
import argparse, datetime, json, os, shutil, sys, zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GENERATED = {"EFC_Styles", "PID_Symbols", "EFC_Library", "EFC_ProcessValues", "PID_Loops"}

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("zips", nargs="+")
    ap.add_argument("--name", help="project folder name (only with a single zip)")
    a = ap.parse_args()
    for zp in a.zips:
        z = zipfile.ZipFile(zp)
        names = [n for n in z.namelist() if not n.endswith("/")]
        if "project.json" not in names:
            sys.exit(f"{zp}: no project.json at the zip root (is it a nested bundle? unzip it and pass the inner project zip)")
        title = a.name or json.loads(z.read("project.json")).get("title") or os.path.splitext(os.path.basename(zp))[0]
        if title in GENERATED:
            sys.exit(f"{zp}: {title} is generated by build.py; change the generator instead")
        dest = os.path.join(ROOT, "imported", title)
        shutil.rmtree(dest, ignore_errors=True)
        for n in names:
            p = os.path.join(dest, n)
            os.makedirs(os.path.dirname(p), exist_ok=True)
            data = z.read(n)
            if n.endswith(".json"):
                data = data.replace(b"\r\n", b"\n").rstrip(b"\n") + b"\n"
            open(p, "wb").write(data)
        log = os.path.join(ROOT, "imported", "IMPORTED.md")
        lines = open(log).read().splitlines() if os.path.exists(log) else [
            "# Imported projects", "", "Added from existing exports with tools/import_project_zip.py; no generator in this repo yet.", "",
            "| Project | Source zip | Imported |", "|---|---|---|"]
        lines = [l for l in lines if not l.startswith(f"| {title} |")] + [f"| {title} | `{os.path.basename(zp)}` | {datetime.date.today()} |"]
        open(log, "w", newline="\n").write("\n".join(lines) + "\n")
        print(f"{zp} -> imported/{title}/ ({len(names)} files)")

if __name__ == "__main__":
    main()
